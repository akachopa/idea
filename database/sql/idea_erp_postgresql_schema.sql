-- IDEA INTEGRATED ERP
-- PostgreSQL 15+
-- Multi-company, multi-branch, single-source-of-truth database.
-- Run on a fresh database.
BEGIN;

-- companies
CREATE TABLE companies (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
code VARCHAR(30) NOT NULL UNIQUE,
name VARCHAR(160) NOT NULL,
legal_name VARCHAR(200),
email VARCHAR(150), phone VARCHAR(50), website VARCHAR(200), address TEXT,
is_active BOOLEAN NOT NULL DEFAULT TRUE,
created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- business_units
CREATE TABLE business_units (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
company_id BIGINT NOT NULL REFERENCES companies(id),
code VARCHAR(30) NOT NULL, name VARCHAR(160) NOT NULL, description TEXT,
is_active BOOLEAN NOT NULL DEFAULT TRUE,
UNIQUE(company_id, code)
);

-- branches
CREATE TABLE branches (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
company_id BIGINT NOT NULL REFERENCES companies(id),
business_unit_id BIGINT REFERENCES business_units(id),
code VARCHAR(30) NOT NULL, name VARCHAR(160) NOT NULL,
branch_type VARCHAR(30) NOT NULL DEFAULT 'CAMPUS',
city_name VARCHAR(100), province_name VARCHAR(100), address TEXT, phone VARCHAR(50), email VARCHAR(150),
is_active BOOLEAN NOT NULL DEFAULT TRUE,
UNIQUE(company_id, code)
);

-- departments
CREATE TABLE departments (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
company_id BIGINT NOT NULL REFERENCES companies(id),
code VARCHAR(30) NOT NULL, name VARCHAR(160) NOT NULL,
parent_id BIGINT REFERENCES departments(id), is_active BOOLEAN NOT NULL DEFAULT TRUE,
UNIQUE(company_id, code)
);

-- positions
CREATE TABLE positions (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
company_id BIGINT NOT NULL REFERENCES companies(id),
department_id BIGINT REFERENCES departments(id),
code VARCHAR(30) NOT NULL, name VARCHAR(160) NOT NULL, level_no INT NOT NULL DEFAULT 1,
is_active BOOLEAN NOT NULL DEFAULT TRUE, UNIQUE(company_id, code)
);

-- countries
CREATE TABLE countries (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
iso2 CHAR(2) NOT NULL UNIQUE, iso3 CHAR(3), name VARCHAR(100) NOT NULL UNIQUE, phone_code VARCHAR(10)
);

-- provinces
CREATE TABLE provinces (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
country_id BIGINT NOT NULL REFERENCES countries(id),
code VARCHAR(30), name VARCHAR(120) NOT NULL, UNIQUE(country_id,name)
);

-- cities
CREATE TABLE cities (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
country_id BIGINT NOT NULL REFERENCES countries(id),
province_id BIGINT REFERENCES provinces(id), code VARCHAR(30), name VARCHAR(120) NOT NULL,
UNIQUE(country_id,name)
);

-- schools
CREATE TABLE schools (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
code VARCHAR(30) UNIQUE, name VARCHAR(180) NOT NULL, school_type VARCHAR(30),
city_id BIGINT REFERENCES cities(id), address TEXT, phone VARCHAR(50), email VARCHAR(150), is_active BOOLEAN DEFAULT TRUE
);

-- persons
CREATE TABLE persons (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
person_code VARCHAR(30) NOT NULL UNIQUE, national_id VARCHAR(50) UNIQUE,
full_name VARCHAR(180) NOT NULL, gender VARCHAR(10), birth_place VARCHAR(120), birth_date DATE,
email VARCHAR(150), phone VARCHAR(50), emergency_phone VARCHAR(50),
nationality_country_id BIGINT REFERENCES countries(id), photo_url TEXT, notes TEXT,
created_at TIMESTAMPTZ DEFAULT NOW(), updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- person_addresses
CREATE TABLE person_addresses (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
person_id BIGINT NOT NULL REFERENCES persons(id) ON DELETE CASCADE,
address_type VARCHAR(20) DEFAULT 'HOME', address TEXT NOT NULL, city_id BIGINT REFERENCES cities(id),
postal_code VARCHAR(20), is_primary BOOLEAN DEFAULT FALSE
);

-- document_types
CREATE TABLE document_types (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
code VARCHAR(30) NOT NULL UNIQUE, name VARCHAR(120) NOT NULL, category VARCHAR(30) NOT NULL,
has_expiry BOOLEAN DEFAULT FALSE, is_required_default BOOLEAN DEFAULT FALSE, is_active BOOLEAN DEFAULT TRUE
);

-- person_documents
CREATE TABLE person_documents (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
person_id BIGINT NOT NULL REFERENCES persons(id) ON DELETE CASCADE,
document_type_id BIGINT NOT NULL REFERENCES document_types(id),
document_no VARCHAR(100), file_url TEXT, issued_date DATE, expiry_date DATE,
verification_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
verified_at TIMESTAMPTZ, notes TEXT
);

-- roles
CREATE TABLE roles (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
code VARCHAR(40) NOT NULL UNIQUE, name VARCHAR(120) NOT NULL, description TEXT, is_active BOOLEAN DEFAULT TRUE
);

-- permissions
CREATE TABLE permissions (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
code VARCHAR(100) NOT NULL UNIQUE, module VARCHAR(50) NOT NULL, name VARCHAR(150) NOT NULL
);

-- users
CREATE TABLE users (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
person_id BIGINT REFERENCES persons(id), company_id BIGINT NOT NULL REFERENCES companies(id),
branch_id BIGINT REFERENCES branches(id), department_id BIGINT REFERENCES departments(id), position_id BIGINT REFERENCES positions(id),
username VARCHAR(80) NOT NULL UNIQUE, email VARCHAR(150) NOT NULL UNIQUE,
password_hash VARCHAR(255) NOT NULL DEFAULT 'DUMMY_REPLACE_WITH_APP_HASH',
is_active BOOLEAN DEFAULT TRUE, last_login_at TIMESTAMPTZ, created_at TIMESTAMPTZ DEFAULT NOW()
);

-- user_roles
CREATE TABLE user_roles (
user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE, PRIMARY KEY(user_id,role_id)
);

-- role_permissions
CREATE TABLE role_permissions (
role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
permission_id BIGINT NOT NULL REFERENCES permissions(id) ON DELETE CASCADE, PRIMARY KEY(role_id,permission_id)
);

-- user_branch_access
CREATE TABLE user_branch_access (
user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
branch_id BIGINT NOT NULL REFERENCES branches(id) ON DELETE CASCADE,
can_view BOOLEAN DEFAULT TRUE, can_edit BOOLEAN DEFAULT FALSE, PRIMARY KEY(user_id,branch_id)
);

-- system_settings
CREATE TABLE system_settings (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
company_id BIGINT REFERENCES companies(id), setting_group VARCHAR(50) NOT NULL, setting_key VARCHAR(100) NOT NULL,
setting_value JSONB NOT NULL DEFAULT '{}'::jsonb, is_secret BOOLEAN DEFAULT FALSE,
updated_by BIGINT REFERENCES users(id), updated_at TIMESTAMPTZ DEFAULT NOW(),
UNIQUE(company_id,setting_group,setting_key)
);

-- audit_logs
CREATE TABLE audit_logs (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
user_id BIGINT REFERENCES users(id), module VARCHAR(50), action VARCHAR(50) NOT NULL,
table_name VARCHAR(100), record_id BIGINT, old_values JSONB, new_values JSONB,
ip_address INET, user_agent TEXT, created_at TIMESTAMPTZ DEFAULT NOW()
);

-- notification_templates
CREATE TABLE notification_templates (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
code VARCHAR(50) NOT NULL UNIQUE, channel VARCHAR(20) NOT NULL,
subject_template TEXT, body_template TEXT NOT NULL, is_active BOOLEAN DEFAULT TRUE
);

-- notifications
CREATE TABLE notifications (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
user_id BIGINT REFERENCES users(id), person_id BIGINT REFERENCES persons(id),
channel VARCHAR(20) NOT NULL, title VARCHAR(180), body TEXT NOT NULL,
reference_type VARCHAR(50), reference_id BIGINT, status VARCHAR(20) DEFAULT 'QUEUED',
sent_at TIMESTAMPTZ, read_at TIMESTAMPTZ, created_at TIMESTAMPTZ DEFAULT NOW()
);

-- approval_workflows
CREATE TABLE approval_workflows (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
code VARCHAR(50) NOT NULL UNIQUE, name VARCHAR(150) NOT NULL, module VARCHAR(50) NOT NULL,
reference_type VARCHAR(50) NOT NULL, is_active BOOLEAN DEFAULT TRUE
);

-- approval_steps
CREATE TABLE approval_steps (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
workflow_id BIGINT NOT NULL REFERENCES approval_workflows(id) ON DELETE CASCADE,
step_no INT NOT NULL, role_id BIGINT REFERENCES roles(id), user_id BIGINT REFERENCES users(id),
minimum_amount NUMERIC(18,2), maximum_amount NUMERIC(18,2), is_required BOOLEAN DEFAULT TRUE,
UNIQUE(workflow_id,step_no)
);

-- approval_requests
CREATE TABLE approval_requests (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
workflow_id BIGINT NOT NULL REFERENCES approval_workflows(id), requested_by BIGINT NOT NULL REFERENCES users(id),
reference_type VARCHAR(50) NOT NULL, reference_id BIGINT NOT NULL, amount NUMERIC(18,2),
current_step_no INT DEFAULT 1, status VARCHAR(20) DEFAULT 'PENDING',
requested_at TIMESTAMPTZ DEFAULT NOW(), completed_at TIMESTAMPTZ
);

-- approval_actions
CREATE TABLE approval_actions (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
approval_request_id BIGINT NOT NULL REFERENCES approval_requests(id) ON DELETE CASCADE,
step_no INT NOT NULL, actor_user_id BIGINT NOT NULL REFERENCES users(id),
action VARCHAR(20) NOT NULL, notes TEXT, acted_at TIMESTAMPTZ DEFAULT NOW()
);

-- programs
CREATE TABLE programs (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
company_id BIGINT NOT NULL REFERENCES companies(id), code VARCHAR(30) NOT NULL, name VARCHAR(160) NOT NULL,
category VARCHAR(50), duration_months INT, description TEXT, is_active BOOLEAN DEFAULT TRUE,
UNIQUE(company_id,code)
);

-- curriculum_versions
CREATE TABLE curriculum_versions (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
program_id BIGINT NOT NULL REFERENCES programs(id), code VARCHAR(30) NOT NULL, name VARCHAR(160) NOT NULL,
effective_from DATE NOT NULL, effective_to DATE, is_active BOOLEAN DEFAULT TRUE, UNIQUE(program_id,code)
);

-- subjects
CREATE TABLE subjects (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
code VARCHAR(30) NOT NULL UNIQUE, name VARCHAR(160) NOT NULL, subject_type VARCHAR(30) DEFAULT 'THEORY',
description TEXT, is_active BOOLEAN DEFAULT TRUE
);

-- curriculum_subjects
CREATE TABLE curriculum_subjects (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
curriculum_version_id BIGINT NOT NULL REFERENCES curriculum_versions(id) ON DELETE CASCADE,
subject_id BIGINT NOT NULL REFERENCES subjects(id), sequence_no INT NOT NULL,
hours_theory NUMERIC(6,2) DEFAULT 0, hours_practical NUMERIC(6,2) DEFAULT 0,
passing_grade NUMERIC(5,2) DEFAULT 70, is_mandatory BOOLEAN DEFAULT TRUE,
UNIQUE(curriculum_version_id,subject_id)
);

-- admission_intakes
CREATE TABLE admission_intakes (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
company_id BIGINT NOT NULL REFERENCES companies(id), branch_id BIGINT NOT NULL REFERENCES branches(id),
code VARCHAR(30) NOT NULL UNIQUE, name VARCHAR(160) NOT NULL,
registration_open DATE NOT NULL, registration_close DATE NOT NULL, start_date DATE NOT NULL, status VARCHAR(20) DEFAULT 'OPEN'
);

-- batches
CREATE TABLE batches (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
program_id BIGINT NOT NULL REFERENCES programs(id), curriculum_version_id BIGINT REFERENCES curriculum_versions(id),
intake_id BIGINT REFERENCES admission_intakes(id), branch_id BIGINT NOT NULL REFERENCES branches(id),
code VARCHAR(30) NOT NULL UNIQUE, name VARCHAR(160) NOT NULL, start_date DATE NOT NULL, end_date DATE,
capacity INT DEFAULT 30, status VARCHAR(20) DEFAULT 'PLANNED'
);

-- classes
CREATE TABLE classes (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
batch_id BIGINT NOT NULL REFERENCES batches(id), code VARCHAR(30) NOT NULL UNIQUE, name VARCHAR(160) NOT NULL,
room_name VARCHAR(100), capacity INT DEFAULT 30, homeroom_user_id BIGINT REFERENCES users(id), status VARCHAR(20) DEFAULT 'ACTIVE'
);

-- applicants
CREATE TABLE applicants (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
company_id BIGINT NOT NULL REFERENCES companies(id), branch_id BIGINT NOT NULL REFERENCES branches(id),
intake_id BIGINT REFERENCES admission_intakes(id), person_id BIGINT NOT NULL REFERENCES persons(id),
registration_no VARCHAR(40) NOT NULL UNIQUE, school_id BIGINT REFERENCES schools(id), graduation_year INT,
source_channel VARCHAR(50), referral_code VARCHAR(50), assigned_user_id BIGINT REFERENCES users(id),
admission_status VARCHAR(30) NOT NULL DEFAULT 'SUBMITTED', submitted_at TIMESTAMPTZ, notes TEXT,
created_at TIMESTAMPTZ DEFAULT NOW(), UNIQUE(person_id,intake_id)
);

-- applicant_program_choices
CREATE TABLE applicant_program_choices (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
applicant_id BIGINT NOT NULL REFERENCES applicants(id) ON DELETE CASCADE,
program_id BIGINT NOT NULL REFERENCES programs(id), branch_id BIGINT NOT NULL REFERENCES branches(id),
priority_no INT DEFAULT 1, is_selected BOOLEAN DEFAULT FALSE, UNIQUE(applicant_id,priority_no)
);

-- admission_verifications
CREATE TABLE admission_verifications (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
applicant_id BIGINT NOT NULL REFERENCES applicants(id) ON DELETE CASCADE,
verified_by BIGINT NOT NULL REFERENCES users(id), verification_type VARCHAR(30) DEFAULT 'ADMINISTRATIVE',
status VARCHAR(20) NOT NULL, checklist JSONB DEFAULT '{}'::jsonb, notes TEXT, verified_at TIMESTAMPTZ DEFAULT NOW()
);

-- admission_interviews
CREATE TABLE admission_interviews (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
applicant_id BIGINT NOT NULL REFERENCES applicants(id) ON DELETE CASCADE,
interviewer_user_id BIGINT NOT NULL REFERENCES users(id), scheduled_at TIMESTAMPTZ NOT NULL,
interview_mode VARCHAR(20) NOT NULL, location_or_link TEXT, overall_score NUMERIC(5,2),
recommendation VARCHAR(30), status VARCHAR(20) DEFAULT 'SCHEDULED', notes TEXT, completed_at TIMESTAMPTZ
);

-- interview_criteria
CREATE TABLE interview_criteria (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
code VARCHAR(30) NOT NULL UNIQUE, name VARCHAR(120) NOT NULL, weight NUMERIC(5,2) DEFAULT 1,
max_score NUMERIC(5,2) DEFAULT 100, is_active BOOLEAN DEFAULT TRUE
);

-- interview_scores
CREATE TABLE interview_scores (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
interview_id BIGINT NOT NULL REFERENCES admission_interviews(id) ON DELETE CASCADE,
criterion_id BIGINT NOT NULL REFERENCES interview_criteria(id), score NUMERIC(5,2) NOT NULL, notes TEXT,
UNIQUE(interview_id,criterion_id)
);

-- admission_decisions
CREATE TABLE admission_decisions (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
applicant_id BIGINT NOT NULL REFERENCES applicants(id) ON DELETE CASCADE,
program_id BIGINT NOT NULL REFERENCES programs(id), decision VARCHAR(20) NOT NULL,
decision_date DATE NOT NULL, decided_by BIGINT NOT NULL REFERENCES users(id), notes TEXT
);

-- registrations
CREATE TABLE registrations (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
applicant_id BIGINT NOT NULL UNIQUE REFERENCES applicants(id) ON DELETE CASCADE,
program_id BIGINT NOT NULL REFERENCES programs(id), batch_id BIGINT REFERENCES batches(id),
registration_date DATE NOT NULL, terms_accepted BOOLEAN DEFAULT FALSE,
registration_status VARCHAR(20) DEFAULT 'PENDING', completed_at TIMESTAMPTZ
);

-- students
CREATE TABLE students (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
company_id BIGINT NOT NULL REFERENCES companies(id), branch_id BIGINT NOT NULL REFERENCES branches(id),
person_id BIGINT NOT NULL UNIQUE REFERENCES persons(id), applicant_id BIGINT UNIQUE REFERENCES applicants(id),
registration_id BIGINT UNIQUE REFERENCES registrations(id), student_no VARCHAR(40) NOT NULL UNIQUE,
program_id BIGINT NOT NULL REFERENCES programs(id), batch_id BIGINT REFERENCES batches(id), class_id BIGINT REFERENCES classes(id),
enrollment_date DATE NOT NULL, student_status VARCHAR(20) DEFAULT 'ACTIVE', created_at TIMESTAMPTZ DEFAULT NOW()
);

-- class_students
CREATE TABLE class_students (
class_id BIGINT NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
joined_date DATE DEFAULT CURRENT_DATE, left_date DATE, PRIMARY KEY(class_id,student_id)
);

-- student_status_history
CREATE TABLE student_status_history (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
old_status VARCHAR(20), new_status VARCHAR(20) NOT NULL, effective_date DATE NOT NULL,
reason TEXT, changed_by BIGINT REFERENCES users(id), created_at TIMESTAMPTZ DEFAULT NOW()
);

-- banks
CREATE TABLE banks (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
code VARCHAR(20) NOT NULL UNIQUE, name VARCHAR(120) NOT NULL, is_active BOOLEAN DEFAULT TRUE
);

-- bank_accounts
CREATE TABLE bank_accounts (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
company_id BIGINT NOT NULL REFERENCES companies(id), bank_id BIGINT NOT NULL REFERENCES banks(id),
branch_id BIGINT REFERENCES branches(id), account_no VARCHAR(80) NOT NULL, account_name VARCHAR(160) NOT NULL,
currency CHAR(3) DEFAULT 'IDR', is_active BOOLEAN DEFAULT TRUE, UNIQUE(bank_id,account_no)
);

-- fee_components
CREATE TABLE fee_components (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
code VARCHAR(30) NOT NULL UNIQUE, name VARCHAR(120) NOT NULL, component_type VARCHAR(30) NOT NULL,
revenue_account_code VARCHAR(30), is_active BOOLEAN DEFAULT TRUE
);

-- program_fee_plans
CREATE TABLE program_fee_plans (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
program_id BIGINT NOT NULL REFERENCES programs(id), branch_id BIGINT REFERENCES branches(id),
intake_id BIGINT REFERENCES admission_intakes(id), code VARCHAR(40) NOT NULL UNIQUE, name VARCHAR(160) NOT NULL,
total_amount NUMERIC(18,2) NOT NULL, currency CHAR(3) DEFAULT 'IDR', is_active BOOLEAN DEFAULT TRUE
);

-- program_fee_plan_items
CREATE TABLE program_fee_plan_items (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
fee_plan_id BIGINT NOT NULL REFERENCES program_fee_plans(id) ON DELETE CASCADE,
fee_component_id BIGINT NOT NULL REFERENCES fee_components(id), sequence_no INT NOT NULL,
amount NUMERIC(18,2) NOT NULL, due_offset_days INT DEFAULT 0, UNIQUE(fee_plan_id,sequence_no)
);

-- student_invoices
CREATE TABLE student_invoices (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
company_id BIGINT NOT NULL REFERENCES companies(id), branch_id BIGINT NOT NULL REFERENCES branches(id),
person_id BIGINT NOT NULL REFERENCES persons(id), applicant_id BIGINT REFERENCES applicants(id), student_id BIGINT REFERENCES students(id),
invoice_no VARCHAR(50) NOT NULL UNIQUE, invoice_date DATE NOT NULL, due_date DATE NOT NULL,
billing_context VARCHAR(20) DEFAULT 'STUDENT', subtotal NUMERIC(18,2) DEFAULT 0,
discount_amount NUMERIC(18,2) DEFAULT 0, total_amount NUMERIC(18,2) DEFAULT 0,
paid_amount NUMERIC(18,2) DEFAULT 0, outstanding_amount NUMERIC(18,2) DEFAULT 0,
status VARCHAR(20) DEFAULT 'UNPAID', notes TEXT, created_at TIMESTAMPTZ DEFAULT NOW()
);

-- student_invoice_items
CREATE TABLE student_invoice_items (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
invoice_id BIGINT NOT NULL REFERENCES student_invoices(id) ON DELETE CASCADE,
fee_component_id BIGINT REFERENCES fee_components(id), description VARCHAR(200) NOT NULL,
qty NUMERIC(10,2) DEFAULT 1, unit_price NUMERIC(18,2) NOT NULL, amount NUMERIC(18,2) NOT NULL
);

-- payments
CREATE TABLE payments (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
company_id BIGINT NOT NULL REFERENCES companies(id), branch_id BIGINT NOT NULL REFERENCES branches(id),
person_id BIGINT REFERENCES persons(id), payment_no VARCHAR(50) NOT NULL UNIQUE, payment_date TIMESTAMPTZ NOT NULL,
payment_method VARCHAR(30) NOT NULL, bank_account_id BIGINT REFERENCES bank_accounts(id),
amount NUMERIC(18,2) NOT NULL, reference_no VARCHAR(100), proof_url TEXT,
verification_status VARCHAR(20) DEFAULT 'PENDING', verified_by BIGINT REFERENCES users(id), verified_at TIMESTAMPTZ, notes TEXT
);

-- payment_allocations
CREATE TABLE payment_allocations (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
payment_id BIGINT NOT NULL REFERENCES payments(id) ON DELETE CASCADE,
invoice_id BIGINT NOT NULL REFERENCES student_invoices(id), allocated_amount NUMERIC(18,2) NOT NULL,
UNIQUE(payment_id,invoice_id)
);

-- scholarships_discounts
CREATE TABLE scholarships_discounts (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
person_id BIGINT NOT NULL REFERENCES persons(id), student_id BIGINT REFERENCES students(id),
type VARCHAR(20) NOT NULL, name VARCHAR(160) NOT NULL, value_type VARCHAR(20) NOT NULL,
value NUMERIC(18,2) NOT NULL, valid_from DATE, valid_to DATE, status VARCHAR(20) DEFAULT 'ACTIVE',
approved_by BIGINT REFERENCES users(id), notes TEXT
);

-- refunds
CREATE TABLE refunds (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
refund_no VARCHAR(50) NOT NULL UNIQUE, person_id BIGINT NOT NULL REFERENCES persons(id),
payment_id BIGINT REFERENCES payments(id), invoice_id BIGINT REFERENCES student_invoices(id),
request_date DATE NOT NULL, amount NUMERIC(18,2) NOT NULL, reason TEXT NOT NULL,
status VARCHAR(20) DEFAULT 'REQUESTED', approved_by BIGINT REFERENCES users(id), paid_at TIMESTAMPTZ
);

-- vendors
CREATE TABLE vendors (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
company_id BIGINT NOT NULL REFERENCES companies(id), code VARCHAR(30) NOT NULL UNIQUE, name VARCHAR(180) NOT NULL,
tax_id VARCHAR(50), contact_name VARCHAR(120), phone VARCHAR(50), email VARCHAR(150), address TEXT, is_active BOOLEAN DEFAULT TRUE
);

-- expense_categories
CREATE TABLE expense_categories (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
code VARCHAR(30) NOT NULL UNIQUE, name VARCHAR(120) NOT NULL, account_code VARCHAR(30), is_active BOOLEAN DEFAULT TRUE
);

-- expenses
CREATE TABLE expenses (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
company_id BIGINT NOT NULL REFERENCES companies(id), branch_id BIGINT REFERENCES branches(id),
department_id BIGINT REFERENCES departments(id), category_id BIGINT NOT NULL REFERENCES expense_categories(id),
vendor_id BIGINT REFERENCES vendors(id), expense_no VARCHAR(50) NOT NULL UNIQUE, expense_date DATE NOT NULL,
description TEXT NOT NULL, amount NUMERIC(18,2) NOT NULL, payment_status VARCHAR(20) DEFAULT 'UNPAID',
approval_status VARCHAR(20) DEFAULT 'PENDING', requested_by BIGINT NOT NULL REFERENCES users(id), paid_at TIMESTAMPTZ
);

-- chart_of_accounts
CREATE TABLE chart_of_accounts (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
company_id BIGINT NOT NULL REFERENCES companies(id), account_code VARCHAR(30) NOT NULL,
account_name VARCHAR(160) NOT NULL, account_type VARCHAR(20) NOT NULL,
parent_id BIGINT REFERENCES chart_of_accounts(id), normal_balance VARCHAR(10) NOT NULL,
is_postable BOOLEAN DEFAULT TRUE, is_active BOOLEAN DEFAULT TRUE, UNIQUE(company_id,account_code)
);

-- journal_entries
CREATE TABLE journal_entries (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
company_id BIGINT NOT NULL REFERENCES companies(id), branch_id BIGINT REFERENCES branches(id),
journal_no VARCHAR(50) NOT NULL UNIQUE, journal_date DATE NOT NULL, source_module VARCHAR(30) NOT NULL,
source_type VARCHAR(50), source_id BIGINT, description TEXT, status VARCHAR(20) DEFAULT 'POSTED',
created_by BIGINT REFERENCES users(id), created_at TIMESTAMPTZ DEFAULT NOW()
);

-- journal_lines
CREATE TABLE journal_lines (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
journal_entry_id BIGINT NOT NULL REFERENCES journal_entries(id) ON DELETE CASCADE,
account_id BIGINT NOT NULL REFERENCES chart_of_accounts(id), department_id BIGINT REFERENCES departments(id),
program_id BIGINT REFERENCES programs(id), description VARCHAR(200),
debit NUMERIC(18,2) DEFAULT 0, credit NUMERIC(18,2) DEFAULT 0
);

-- schedules
CREATE TABLE schedules (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
class_id BIGINT NOT NULL REFERENCES classes(id), subject_id BIGINT NOT NULL REFERENCES subjects(id),
trainer_user_id BIGINT REFERENCES users(id), schedule_date DATE NOT NULL, start_time TIME NOT NULL, end_time TIME NOT NULL,
room_name VARCHAR(100), delivery_mode VARCHAR(20) DEFAULT 'ONSITE', status VARCHAR(20) DEFAULT 'SCHEDULED'
);

-- attendance
CREATE TABLE attendance (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
schedule_id BIGINT NOT NULL REFERENCES schedules(id) ON DELETE CASCADE,
student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
check_in_at TIMESTAMPTZ, check_out_at TIMESTAMPTZ, status VARCHAR(20) NOT NULL,
method VARCHAR(20) DEFAULT 'MANUAL', notes TEXT, UNIQUE(schedule_id,student_id)
);

-- learning_materials
CREATE TABLE learning_materials (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
subject_id BIGINT NOT NULL REFERENCES subjects(id), title VARCHAR(180) NOT NULL, material_type VARCHAR(30) NOT NULL,
url TEXT, description TEXT, is_active BOOLEAN DEFAULT TRUE, created_by BIGINT REFERENCES users(id)
);

-- assignments
CREATE TABLE assignments (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
class_id BIGINT NOT NULL REFERENCES classes(id), subject_id BIGINT NOT NULL REFERENCES subjects(id),
title VARCHAR(180) NOT NULL, description TEXT, due_at TIMESTAMPTZ NOT NULL,
max_score NUMERIC(5,2) DEFAULT 100, created_by BIGINT REFERENCES users(id)
);

-- assignment_submissions
CREATE TABLE assignment_submissions (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
